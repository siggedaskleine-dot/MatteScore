export function countryName(c: string) {
  return C[c]?.[0] ?? c.replace(/-/g, ' ');
}

export function countryFlag(c: string) {
  const code = C[c]?.[1];
  if (!code) return '🌍';
  if (code === 'EU') return '🇪🇺';
  return String.fromCodePoint(...[...code].map((ch) => 0x1f1e6 + ch.charCodeAt(0) - 65));
}
